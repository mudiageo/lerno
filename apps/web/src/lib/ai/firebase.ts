/**
 * Firebase AI Logic client for Lerno's hybrid features.
 *
 * This module is browser-only. It deliberately does not initialise Firebase at
 * import time so SSR/builds can import route modules safely. Call one of the
 * exported helpers from an event handler or an `onMount`/effect context.
 */

import { browser, dev } from '$app/env';
import {
  FIREBASE_API_KEY,
  FIREBASE_APPCHECK_DEBUG,
  FIREBASE_APPCHECK_PROVIDER,
  FIREBASE_APPCHECK_SITE_KEY,
  FIREBASE_AUTH_DOMAIN,
  FIREBASE_APP_ID,
  FIREBASE_PROJECT_ID,
} from '$app/env/public';
import { getApps, initializeApp, type FirebaseApp } from 'firebase/app';
import {
  initializeAppCheck,
  ReCaptchaEnterpriseProvider,
  ReCaptchaV3Provider,
} from 'firebase/app-check';
import {
  getAI,
  getGenerativeModel,
  GoogleAIBackend,
  InferenceMode,
  InferenceSource,
  SchemaType,
  type AI,
  type GenerativeModel,
  type GenerationConfig,
  type HybridParams,
  type InferenceMode as InferenceModeValue,
  type InferenceSource as InferenceSourceValue,
  type ModelParams,
  type Part,
  type SchemaRequest,
} from 'firebase/ai';

const DEFAULT_CLOUD_MODEL = 'gemini-3.5-flash-lite';
const APP_NAME = 'lerno-hybrid-ai';
const MAX_IMAGE_BYTES = 4 * 1024 * 1024;

export const HYBRID_MODES = {
  private: InferenceMode.ONLY_ON_DEVICE,
  hybrid: InferenceMode.PREFER_ON_DEVICE,
  balanced: InferenceMode.PREFER_IN_CLOUD,
  deep: InferenceMode.ONLY_IN_CLOUD,
} as const;

export type LernoInferenceMode = keyof typeof HYBRID_MODES;
export type DisplayInferenceSource = InferenceSourceValue | 'unknown';

export interface FirebasePublicConfig {
  apiKey: string;
  authDomain: string;
  projectId: string;
  appId: string;
}

export interface HybridImage {
  mimeType: 'image/jpeg' | 'image/png';
  data: string;
}

export interface OnDeviceCapability {
  status: 'available' | 'downloadable' | 'downloading' | 'unavailable' | 'unsupported';
  supported: boolean;
  label: string;
  detail: string;
}

export interface HybridGenerateOptions {
  prompt: string;
  mode?: LernoInferenceMode;
  systemInstruction?: string;
  cloudModel?: string;
  responseJsonSchema?: SchemaRequest;
  images?: HybridImage[];
  onDownloadProgress?: (progress: number) => void;
}

export interface HybridGenerationResult {
  text: string;
  json?: unknown;
  inferenceSource: DisplayInferenceSource;
  mode: LernoInferenceMode;
}

interface ChromeLanguageModel {
  availability?: () => Promise<OnDeviceCapability['status']>;
}

type FirebaseDebugWindow = typeof globalThis & {
  FIREBASE_APPCHECK_DEBUG_TOKEN?: boolean | string;
};

let appCheckInitialised = false;
let cachedAI: AI | undefined;

function envValue(value: string | undefined): string {
  return typeof value === 'string' ? value.trim() : '';
}

/** Treat scaffold values as missing so a placeholder build never pretends to be live. */
function isPlaceholder(value: string): boolean {
  if (!value) return true;
  return (
    /^REPLACE_/i.test(value) ||
    /^your[-_]/i.test(value) ||
    /^xxx+$/i.test(value) ||
    /^<.*>$/.test(value) ||
    /^AIza\.\.\.$/.test(value)
  );
}

/** Firebase web config is public by design. It is not an API secret. */
export function getFirebasePublicConfig(): FirebasePublicConfig | null {
  const config: FirebasePublicConfig = {
    apiKey: envValue(FIREBASE_API_KEY),
    authDomain: envValue(FIREBASE_AUTH_DOMAIN),
    projectId: envValue(FIREBASE_PROJECT_ID),
    appId: envValue(FIREBASE_APP_ID),
  };

  const values = Object.values(config);
  return values.every((value) => value && !isPlaceholder(value)) ? config : null;
}

export function isFirebaseAIConfigured(): boolean {
  return getFirebasePublicConfig() !== null;
}

function initialiseAppCheck(app: FirebaseApp): void {
  if (appCheckInitialised) return;

  const debugEnabled = dev && envValue(FIREBASE_APPCHECK_DEBUG) === 'true';
  const siteKey = envValue(FIREBASE_APPCHECK_SITE_KEY);

  if (!debugEnabled && !siteKey) {
    throw new Error(
      'Firebase App Check is required. Set FIREBASE_APPCHECK_SITE_KEY, or enable the local debug provider.'
    );
  }

  if (debugEnabled) {
    // Must be set before initializeAppCheck. The token is generated by the
    // browser and safelisted in the Firebase console; never commit it.
    (self as FirebaseDebugWindow).FIREBASE_APPCHECK_DEBUG_TOKEN = true;
  }

  const providerName = envValue(FIREBASE_APPCHECK_PROVIDER) || 'recaptcha-v3';
  const key = siteKey || 'app-check-debug-provider';
  let provider: ReCaptchaV3Provider | ReCaptchaEnterpriseProvider;

  if (providerName === 'recaptcha-enterprise') {
    // Google Cloud Fraud Defense (formerly reCAPTCHA Enterprise).
    provider = new ReCaptchaEnterpriseProvider(key);
  } else if (providerName === 'recaptcha-v3') {
    provider = new ReCaptchaV3Provider(key);
  } else {
    throw new Error(
      `Unknown FIREBASE_APPCHECK_PROVIDER "${providerName}". Use recaptcha-v3 or recaptcha-enterprise.`
    );
  }

  initializeAppCheck(app, {
    provider,
    isTokenAutoRefreshEnabled: true,
  });

  appCheckInitialised = true;
}

function getFirebaseApp(): FirebaseApp {
  if (!browser) {
    throw new Error('Firebase AI Logic is only available in the browser.');
  }

  const config = getFirebasePublicConfig();
  if (!config) {
    throw new Error(
      'Firebase AI Logic is not configured. Add the FIREBASE_* values from the Firebase web app config.'
    );
  }

  const existing = getApps().find((app) => app.name === APP_NAME);
  const app = existing ?? initializeApp(config, APP_NAME);
  initialiseAppCheck(app);
  return app;
}

/** Returns the configured Firebase AI Logic client using the Gemini Developer API backend. */
export function getLernoAI(): AI {
  if (cachedAI) return cachedAI;
  cachedAI = getAI(getFirebaseApp(), {
    backend: new GoogleAIBackend(),
    useLimitedUseAppCheckTokens: true,
  });
  return cachedAI;
}

export function createHybridModel(
  options: {
    mode?: LernoInferenceMode;
    cloudModel?: string;
    responseJsonSchema?: SchemaRequest;
  } = {}
): GenerativeModel {
  const mode = options.mode ?? 'hybrid';
  const inferenceMode = HYBRID_MODES[mode];
  const cloudModel = options.cloudModel ?? DEFAULT_CLOUD_MODEL;

  const inCloudParams: ModelParams = {
    model: cloudModel,
    ...(options.responseJsonSchema
      ? {
          generationConfig: {
            responseMimeType: 'application/json',
            responseSchema: options.responseJsonSchema,
          } satisfies GenerationConfig,
        }
      : {}),
  };

  const onDeviceParams = options.responseJsonSchema
    ? { promptOptions: { responseConstraint: options.responseJsonSchema } }
    : undefined;

  const params: HybridParams = {
    mode: inferenceMode as InferenceModeValue,
    inCloudParams,
    ...(onDeviceParams ? { onDeviceParams } : {}),
  };

  return getGenerativeModel(getLernoAI(), params);
}

/**
 * Detects whether Chrome's Prompt API is present. Tauri webviews and non-Chrome
 * browsers return `unsupported`, which is an expected cloud-fallback case.
 */
export async function getOnDeviceCapability(): Promise<OnDeviceCapability> {
  if (!browser) {
    return {
      status: 'unsupported',
      supported: false,
      label: 'Checking on-device model…',
      detail: 'Capability is checked in the browser.',
    };
  }

  const languageModel = (globalThis as typeof globalThis & { LanguageModel?: ChromeLanguageModel })
    .LanguageModel;

  if (!languageModel?.availability) {
    return {
      status: 'unsupported',
      supported: false,
      label: 'On-device model unavailable',
      detail: 'This browser has no Chrome Prompt API. Answers will use cloud inference.',
    };
  }

  try {
    const status = await languageModel.availability();
    if (status === 'available') {
      return {
        status,
        supported: true,
        label: 'On-device model ready',
        detail: 'Private answers can stay on this device.',
      };
    }
    if (status === 'downloadable' || status === 'downloading') {
      return {
        status,
        supported: true,
        label:
          status === 'downloading'
            ? 'On-device model downloading'
            : 'On-device model can be downloaded',
        detail: 'Tap Prepare model on a click to download it before generating.',
      };
    }
    return {
      status,
      supported: false,
      label: 'On-device model unavailable',
      detail: 'This device cannot run Nano right now. Hybrid mode will use cloud inference.',
    };
  } catch {
    return {
      status: 'unavailable',
      supported: false,
      label: 'On-device model unavailable',
      detail: 'Capability detection failed. Hybrid mode will use cloud inference.',
    };
  }
}

/** Call from a user gesture; Chrome blocks model downloads without one. */
export async function prepareOnDeviceModel(
  onDownloadProgress?: (progress: number) => void
): Promise<void> {
  const model = createHybridModel({ mode: 'hybrid' });
  await model.initializeDeviceModel(onDownloadProgress);
}

export function inferenceSourceLabel(source: DisplayInferenceSource): string {
  if (source === InferenceSource.ON_DEVICE) return 'ON_DEVICE';
  if (source === InferenceSource.IN_CLOUD) return 'IN_CLOUD';
  return 'UNKNOWN';
}

export function isOnDeviceSource(source: DisplayInferenceSource): boolean {
  return source === InferenceSource.ON_DEVICE;
}

/** Converts a JPEG/PNG File into the inlineData shape expected by Firebase AI Logic. */
export async function fileToHybridImage(file: File): Promise<HybridImage> {
  if (file.type !== 'image/jpeg' && file.type !== 'image/png') {
    throw new Error('Use a JPEG or PNG image.');
  }
  if (file.size > MAX_IMAGE_BYTES) {
    throw new Error('Image is larger than 4 MB. Choose a smaller photo.');
  }

  const dataUrl = await new Promise<string>((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(String(reader.result));
    reader.onerror = () => reject(reader.error ?? new Error('Could not read image.'));
    reader.readAsDataURL(file);
  });

  return {
    mimeType: file.type,
    data: dataUrl.slice(dataUrl.indexOf(',') + 1),
  };
}

function buildParts(prompt: string, images: HybridImage[] = []): Part[] {
  const parts: Part[] = [{ type: 'text', text: prompt }];
  for (const image of images) {
    parts.push({
      type: 'inlineData',
      inlineData: { mimeType: image.mimeType, data: image.data },
    });
  }
  return parts;
}

/**
 * Single entry point for all judged inference. The caller chooses the mode;
 * the returned `inferenceSource` proves where the answer actually ran.
 */
export async function generateWithFirebaseAI(
  options: HybridGenerateOptions
): Promise<HybridGenerationResult> {
  const mode = options.mode ?? 'hybrid';
  const model = createHybridModel({
    mode,
    cloudModel: options.cloudModel,
    responseJsonSchema: options.responseJsonSchema,
  });

  if (mode === 'private') {
    try {
      await model.initializeDeviceModel(options.onDownloadProgress);
    } catch {
      throw new Error('No on-device model is available. Use Hybrid mode to allow cloud fallback.');
    }
  } else if (mode === 'hybrid') {
    // Do not block the first response on a multi-minute download. The SDK
    // falls back to cloud automatically while the device model downloads.
    void model.initializeDeviceModel(options.onDownloadProgress).catch((error) => {
      console.info('On-device model not ready; cloud fallback is available.', error);
    });
  }

  const prompt = options.systemInstruction
    ? `${options.systemInstruction}\n\n${options.prompt}`
    : options.prompt;

  const result = await model.generateContent({
    contents: [{ role: 'user', parts: buildParts(prompt, options.images) }],
  });

  const text = result.response.text();
  let json: unknown;
  if (options.responseJsonSchema) {
    try {
      json = JSON.parse(text);
    } catch {
      throw new Error('The model returned invalid JSON. Try again with a clearer prompt.');
    }
  }

  return {
    text,
    json,
    inferenceSource: result.response.inferenceSource ?? 'unknown',
    mode,
  };
}

